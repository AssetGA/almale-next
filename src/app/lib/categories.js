export function categoryCopy(lang, slug) {
  const locale = copy[lang] ? lang : "ru";
  return copy[locale][slug] || null;
}

export function homeOffer(lang) {
  const locale = copy[lang] ? lang : "ru";
  return { text: copy[locale].home, price: copy[locale].price };
}

export function categoryNav(lang) {
  const locale = copy[lang] ? lang : "ru";
  return categorySlugs.map((slug) => ({
    slug,
    label: copy[locale][slug].nav,
  }));
}
